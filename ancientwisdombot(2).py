def fetch_ai_news(query: str, num_articles: int = 3) -> dict:
    try:
        # Calculate date range — last 7 days only
        today = datetime.now().strftime('%Y-%m-%d')
        week_ago = (datetime.now() - timedelta(days=7)).strftime('%Y-%m-%d')

        r = requests.get(
            'https://newsapi.org/v2/everything',
            params={
                'q':        query,
                'language': 'en',
                'sortBy':   'publishedAt',  # most recent first
                'from':     week_ago,        # last 7 days only
                'to':       today,
                'pageSize': min(num_articles, 5),
                'apiKey':   newsData_API_KEY
            },
            timeout=10
        )
        data = r.json()
        if data.get('status') != 'ok':
            return {'error': data.get('message', 'NewsAPI error')}
        articles = [
            {
                'title':       a.get('title', ''),
                'source':      a.get('source', {}).get('name', ''),
                'published':   a.get('publishedAt', '')[:10],
                'description': a.get('description', ''),
                'content':     a.get('content', ''),
                'url':         a.get('url', '')
            }
            for a in data.get('articles', [])
        ]


        if not articles :
            print('  News API empty — trying The Guardian...')
            return fetch_guardian_news(query, num_papers)

        return {'articles': articles, 'total_results': data.get('totalResults', 0)}

    except Exception as e:
        print(f'  News API error ({e}) — trying The Guardian...')
        return fetch_guardian_news(query, num_articles)


def fetch_guardian_news(query: str, num_articles: int = 3) -> dict:
    """
    I define a backup news source : The Guardian API.
    It's free, has no rate limits and covers the latest news in AI Ethics.
    """
    try:
        r = requests.get(
            'https://content.guardianapis.com/search',
            params={
                'q':                query,
                'section':          'technology',
                'order-by':         'newest',
                'show-fields':      'headline,trailText,bodyText',
                'page-size':        min(num_articles, 5),
                'api-key':          'test'  # 'test' key works for dev
            },
            timeout=10
        )
        data = r.json()
        articles = [
            {
                'title':       a.get('webTitle', ''),
                'source':      'The Guardian',
                'published':   a.get('webPublicationDate', '')[:10],
                'description': a.get('fields', {}).get('trailText', ''),
                'content':     a.get('fields', {}).get('bodyText', '')[:500],
                'url':         a.get('webUrl', '')
            }
            for a in data.get('response', {}).get('results', [])
        ]
        return {'articles': articles}
    except Exception as e:
        return {'error': str(e)}

