def dispatch_function(name: str, arguments: str) -> str:
    """
    This dispacth function will execute the function the LLM requested and then return the result in JSON.

    LLM returns a function_call with name + arguments, the dispatcher looks it up, parses the argument, runs it- retunrs the result as a JSON string and appends it as function_call_output to the dialogue.

    """
    print(f'Dispatching: {name}')

    if name not in FUNCTION_MAP:
        error = {'error': f'Unknown function requested: {name}'}
        print(f'{error}')
        return json.dumps(error)

    try:
        # Arguments arrive as a JSON strin, parse to dict
        args = json.loads(arguments) if isinstance(arguments, str) else arguments
        print(f'       Args: {json.dumps(args)}')

        # Run the real Python function
        result = FUNCTION_MAP[name](**args)
        print(f'       Result preview: {str(result)[:100]}...')

        # Return as JSON string as required by the Responses API
        return json.dumps(result, default=str)

    except Exception as e:
        error = {'error': f'Function execution failed: {str(e)}'}
        print(f' {error}')
        return json.dumps(error)


